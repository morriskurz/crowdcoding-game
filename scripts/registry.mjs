// Game registry generator. Every directory packages/games/<slug>/ with an index.ts and a
// package.json is a game; nothing has to be registered by hand, so the weekly bootstrap only adds
// a directory. Writes (all git-ignored, regenerated on every install and client build):
//   packages/registry/games.gen.ts   static imports of every game, for @tcg/games (server, present)
//   apps/client/games/<slug>.html    one sandboxed game page per game (Vite entry), served at /<slug>/game
//   apps/client/games/<slug>.ts      its entry: the frozen renderer + that game's rules and assets
//
// Current game = the newest `tcg.created` (package.json), ties broken by slug. `orchestrate.mjs bootstrap`
// stamps it, so a merged bootstrap becomes this week's game and the previous one is archived.
//
// Run: node scripts/registry.mjs [root]   (root postinstall, apps/client/vite.config.ts, gates.mjs and
// present/server.mjs call it; it rewrites a file only when its content changes).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const SLUG_RE = /^[a-z0-9][a-z0-9-]{0,39}$/;
// First path segments the Worker, the client build and the room router already use.
export const RESERVED = new Set(["game", "games", "assets", "parties", "health", "drain", "main", "src", "index", "registry"]);

export const isGameSlug = (s) => typeof s === "string" && SLUG_RE.test(s) && !RESERVED.has(s);

/**
 * One game directory -> {slug, title, created}, or null (with a warning) when it is not a game.
 * `pkgText` is its package.json content (null if missing). Shared by listGames (working tree) and
 * guard.mjs (a git ref), so both pick the same current game.
 */
export function gameEntry(name, hasIndex, pkgText, warn = () => {}) {
  if (!isGameSlug(name)) { warn(`registry: skipping packages/games/${name} (slug must match ${SLUG_RE} and not be reserved)`); return null; }
  if (!hasIndex) { warn(`registry: skipping packages/games/${name} (no index.ts)`); return null; }
  let meta = {};
  try { meta = JSON.parse(pkgText ?? "").tcg ?? {}; }
  catch { warn(`registry: skipping packages/games/${name} (no readable package.json)`); return null; }
  const title = typeof meta.title === "string" && meta.title.trim() ? meta.title.trim().slice(0, 60) : name;
  const created = typeof meta.created === "string" && !Number.isNaN(Date.parse(meta.created)) ? new Date(meta.created).toISOString() : "";
  return { slug: name, title, created };
}

/** Oldest first (the last one is current): by `created`, ties broken by slug. */
export const sortGames = (games) => games.sort((a, b) => a.created.localeCompare(b.created) || a.slug.localeCompare(b.slug));

/** All games, oldest first (the last one is current). Invalid directories are skipped with a warning. */
export function listGames(root = process.cwd(), warn = (m) => console.warn(m)) {
  const dir = path.join(root, "packages/games");
  if (!fs.existsSync(dir)) return [];
  const games = [];
  for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name === "node_modules") continue;
    const base = path.join(dir, d.name);
    let pkg = null;
    try { pkg = fs.readFileSync(path.join(base, "package.json"), "utf8"); } catch { /* reported by gameEntry */ }
    const g = gameEntry(d.name, fs.existsSync(path.join(base, "index.ts")), pkg, warn);
    if (g) games.push(g);
  }
  return sortGames(games);
}

export const currentSlug = (games) => games.at(-1)?.slug ?? null;

const HEADER = "// GENERATED by scripts/registry.mjs from packages/games/*. Do not edit; not committed.\n";

export function registrySource(games) {
  const lines = [HEADER];
  games.forEach((g, i) => lines.push(`import * as g${i} from "../games/${g.slug}/index.js";`));
  lines.push("", `export const CURRENT_SLUG = ${JSON.stringify(currentSlug(games) ?? "")};`, "", "export const GAME_LIST = [");
  games.forEach((g, i) => lines.push(`  { slug: ${JSON.stringify(g.slug)}, title: ${JSON.stringify(g.title)}, created: ${JSON.stringify(g.created)}, module: g${i} },`));
  lines.push("] as const;", "");
  return lines.join("\n");
}

export function gamePageSource(game) {
  return `<!doctype html>
<!-- GENERATED by scripts/registry.mjs. Do not edit. -->
<html>
<head><meta charset="utf-8"/><meta name="viewport" content="width=device-width,initial-scale=1"/>
<title>${game.title.replace(/[<>&"]/g, "")}</title>
</head>
<body>
<canvas id="c"></canvas>
<script type="module" src="./${game.slug}.ts"></script>
</body>
</html>
`;
}

export function gameEntrySource(game) {
  return `${HEADER}import { startGame } from "../src/game/main.js";
import { assets, rules } from "../../../packages/games/${game.slug}/index.js";

startGame(rules, assets);
`;
}

function writeIfChanged(file, content, changed) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  changed.push(file);
}

/** Write every generated file for `root`. Returns {games, current, changed}. */
export function writeRegistry(root = process.cwd(), warn) {
  const games = listGames(root, warn);
  const changed = [];
  const reg = path.join(root, "packages/registry");
  if (fs.existsSync(reg)) writeIfChanged(path.join(reg, "games.gen.ts"), registrySource(games), changed);
  const client = path.join(root, "apps/client");
  if (fs.existsSync(client)) {
    const out = path.join(client, "games");
    const keep = new Set();
    for (const g of games) {
      for (const [name, src] of [[`${g.slug}.html`, gamePageSource(g)], [`${g.slug}.ts`, gameEntrySource(g)]]) {
        keep.add(name);
        writeIfChanged(path.join(out, name), src, changed);
      }
    }
    // A removed game's page must not linger in the next build.
    if (fs.existsSync(out)) for (const f of fs.readdirSync(out)) if (!keep.has(f)) { fs.rmSync(path.join(out, f), { force: true }); changed.push(path.join(out, f)); }
  }
  return { games, current: currentSlug(games), changed };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const root = path.resolve(process.argv[2] ?? path.join(path.dirname(fileURLToPath(import.meta.url)), ".."));
  const r = writeRegistry(root);
  if (!r.games.length) { console.error("registry: no games under packages/games"); process.exit(1); }
  console.log(`registry: ${r.games.length} game(s), current ${r.current}${r.changed.length ? `, wrote ${r.changed.length} file(s)` : ""}`);
}
